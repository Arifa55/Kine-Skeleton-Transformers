"""**Reasoning**:
To create the `SimpleSSMLayer` as requested, I need to import the `Layer` class from TensorFlow Keras and define the basic class structure.


"""

import tensorflow as tf
from tensorflow.keras.layers import Layer

class SimpleSSMLayer(Layer):
    def __init__(self, d_model, state_size, **kwargs):
        super().__init__(**kwargs)
        self.d_model = d_model
        self.state_size = state_size

    def build(self, input_shape):
        # State matrix A: (state_size, state_size)
        self.A = self.add_weight(
            shape=(self.state_size, self.state_size),
            initializer='identity',
            trainable=True,
            name='A_matrix'
        )
        # Input matrix B: (state_size, d_model)
        self.B = self.add_weight(
            shape=(self.state_size, self.d_model),
            initializer='random_normal',
            trainable=True,
            name='B_matrix'
        )
        # Output matrix C: (d_model, state_size)
        self.C = self.add_weight(
            shape=(self.d_model, self.state_size),
            initializer='random_normal',
            trainable=True,
            name='C_matrix'
        )
        # Direct feedthrough matrix D: (d_model, d_model)
        self.D = self.add_weight(
            shape=(self.d_model, self.d_model),
            initializer='identity',
            trainable=True,
            name='D_matrix'
        )
        self.built = True

    def call(self, inputs):
        # inputs shape: (batch_size, sequence_length, d_model)
        batch_size = tf.shape(inputs)[0]
        sequence_length = tf.shape(inputs)[1]

        # Initial hidden state h0
        h0 = tf.zeros((batch_size, self.state_size))

        # Define the scan function for one time step
        def scan_fn(carry, x_t):
            h_prev = carry  # h_{t-1}

            # Recurrent hidden state update: h_t = A * h_{t-1} + B * x_t
            h_t = tf.matmul(h_prev, self.A, transpose_b=True) + tf.matmul(x_t, self.B, transpose_b=True)

            # Output calculation: y_t = C * h_t + D * x_t
            y_t = tf.matmul(h_t, self.C, transpose_b=True) + tf.matmul(x_t, self.D, transpose_b=True)

            return h_t, y_t

        # Transpose inputs to (sequence_length, batch_size, d_model) for tf.scan
        # and then process each x_t in the sequence
        inputs_transposed = tf.transpose(inputs, perm=[1, 0, 2])

        # Apply tf.scan over the sequence
        _, outputs_sequence = tf.scan(
            fn=scan_fn,
            elems=inputs_transposed,
            initializer=h0
        )

        # Transpose outputs back to (batch_size, sequence_length, d_model)
        outputs = tf.transpose(outputs_sequence, perm=[1, 0, 2])
        return outputs

