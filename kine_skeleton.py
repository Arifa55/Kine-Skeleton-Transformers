# Define padding function for a single video's frames
def pad_video_frames(video_poses, max_frames, max_pose_dim):
    padded_frames = []
    for frame_pose in video_poses:
        # Pad each frame's pose vector to max_pose_dim
        padded_frame_pose = np.pad(frame_pose, (0, max_pose_dim - len(frame_pose)), 'constant', constant_values=0)
        padded_frames.append(padded_frame_pose)

    # Pad the list of frames to max_frames
    while len(padded_frames) < max_frames:
        padded_frames.append(np.zeros(max_pose_dim))

    return np.array(padded_frames)

